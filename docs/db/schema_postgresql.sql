CREATE OR REPLACE FUNCTION smartmart.fn_updated_at()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$ BEGIN NEW.ngay_cap_nhat:=clock_timestamp(); RETURN NEW; END $function$
;
CREATE OR REPLACE FUNCTION smartmart.fn_prevent_history_mutation()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
BEGIN
  RAISE EXCEPTION USING ERRCODE='23514',
    MESSAGE=format('%s is append-only: %s forbidden', TG_TABLE_NAME, TG_OP);
END;
$function$
;
CREATE OR REPLACE FUNCTION smartmart.fn_guard_hoa_don()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
BEGIN
  IF TG_OP='DELETE' THEN
    RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='hoa_don cannot be deleted';
  END IF;
  IF OLD.trang_thai IS DISTINCT FROM 'DA_THANH_TOAN'
     OR NEW.trang_thai IS DISTINCT FROM 'DA_HUY'
     OR (to_jsonb(NEW) - ARRAY['trang_thai','nguoi_huy_id','huy_luc','ly_do_huy']::text[])
        IS DISTINCT FROM
        (to_jsonb(OLD) - ARRAY['trang_thai','nguoi_huy_id','huy_luc','ly_do_huy']::text[])
  THEN
    RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='hoa_don only permits cancellation with immutable financial snapshot';
  END IF;
  RETURN NEW;
END;
$function$
;
